"""
Independent check of Rick's Theorems A and B (0-Hecke indecomposability), 2026-11-12 REVIEW.

Mechanism (deliberately different from Rick's word model / Mackey split):
  * Theorem A: M_{I,J} = H_N(0) (x)_B C_chi is built as a QUOTIENT of the regular
    representation of H_N(0) (basis pi_w, w in S_N) by the left ideal generated by
    pi_i - chi(i), i != a.  No shuffle words are used.
  * Theorem B: X_{lambda/mu} is built from the KLO App. A tableau rule on SYT.
  * End(M) is obtained by Frobenius reciprocity from Hom_B(V, Res M) where V is a
    generating B-submodule, extended along the H_N-action by BFS, and every candidate
    endomorphism is then CHECKED to commute with every pi_i (so a wrong extension
    cannot pass).  dim M = [H_N:B]-index * dim V and BFS-generation certify M = Ind V.
  * Number of indecomposable summands t = dim End/J(End), computed as the rank of the
    trace form Tr(L_{xy}) of the LEFT REGULAR representation of End (Dickson's criterion;
    valid in char 0, here mod a prime p >> dim End).  Indecomposable <=> t = 1.
    Rick's proof never uses this quantity.
All arithmetic mod the prime P = 33554393.
"""
import itertools, sys
import numpy as np

P = 33554393   # prime < 2^25: int64 matmul of d<=8000 cannot overflow


# ---------------------------------------------------------------- linear algebra mod P
def rref(A):
    """Row-reduce A (rows mod P) with numpy int64. Return (R as list of lists, pivots)."""
    A = np.array(A, dtype=np.int64) % P
    if A.ndim == 1:
        A = A.reshape(1, -1)
    nr, nc = A.shape
    piv = []; r = 0
    for c in range(nc):
        if r == nr:
            break
        nz = np.nonzero(A[r:, c])[0]
        if nz.size == 0:
            continue
        pr = r + nz[0]
        if pr != r:
            A[[r, pr]] = A[[pr, r]]
        inv = pow(int(A[r, c]), P - 2, P)
        A[r] = (A[r] * inv) % P
        col = A[:, c].copy(); col[r] = 0
        rows = np.nonzero(col)[0]
        if rows.size:
            # A[rows] -= col[rows] (outer) A[r]; split multiply to stay < 2^63
            A[rows] = (A[rows] - (col[rows, None] * A[r][None, :]) % P) % P
        piv.append(c); r += 1
    return A[:r].tolist(), piv


def nullspace(A, ncols):
    """Basis of {x : A x = 0} as list of vectors (length ncols)."""
    if not A:
        return [[1 if j == i else 0 for j in range(ncols)] for i in range(ncols)]
    R, piv = rref(A)
    free = [c for c in range(ncols) if c not in set(piv)]
    basis = []
    for f in free:
        x = [0] * ncols; x[f] = 1
        for row, pc in zip(R, piv):
            x[pc] = (-row[f]) % P
        basis.append(x)
    return basis


def rank(A):
    if not A:
        return 0
    return len(rref(A)[0])


def matmul(A, B):
    return (np.array(A, dtype=object).dot(np.array(B, dtype=object))) % P


# ---------------------------------------------------------------- generic machinery
class Module:
    """Module with basis 0..d-1; act[i][b] = list of (coef, b') giving pi_{i+1} e_b."""
    def __init__(self, d, n, act):
        self.d, self.n, self.act = d, n, act

    def mat(self, i):
        M = [[0] * self.d for _ in range(self.d)]
        for b in range(self.d):
            for c, bb in self.act[i][b]:
                M[bb][b] = (M[bb][b] + c) % P
        return M

    def apply(self, i, vec):
        out = [0] * self.d
        for b, x in enumerate(vec):
            if x:
                for c, bb in self.act[i][b]:
                    out[bb] = (out[bb] + c * x) % P
        return out

    def check_relations(self):
        """pi_i^2 = pi_i, braid, commuting."""
        mats = [np.array(self.mat(i), dtype=object) for i in range(self.n - 1)]
        for i, A in enumerate(mats):
            assert ((A.dot(A) - A) % P == 0).all(), "pi^2"
            for j, B in enumerate(mats):
                if j == i + 1:
                    assert ((A.dot(B).dot(A) - B.dot(A).dot(B)) % P == 0).all(), "braid"
                if j > i + 1:
                    assert ((A.dot(B) - B.dot(A)) % P == 0).all(), "comm"
        return True


def endomorphisms(M, gens, B_idx):
    """
    End_{H_n}(M) via Frobenius: M is generated by the B-submodule V = span(gens) of basis
    vectors; B is generated by pi_i, i in B_idx (0-based).  Solve U A_V = A_M U for
    U : V -> M (Kronecker form, constraints imposed one generator at a time), extend
    along monomial moves by BFS, and VERIFY each extension commutes with every pi_i.
    """
    d = M.d; g = len(gens); pos = {b: k for k, b in enumerate(gens)}
    for i in B_idx:
        for b in gens:
            for c, bb in M.act[i][b]:
                assert bb in pos, "gens not B-stable"
    nv = d * g                       # vec(U) column-major: U[x,k] -> k*d + x
    N = np.eye(nv, dtype=np.int64)
    for i in B_idx:
        AM = np.array(M.mat(i), dtype=np.int64)
        AV = np.zeros((g, g), dtype=np.int64)
        for k, b in enumerate(gens):
            for c, bb in M.act[i][b]:
                AV[pos[bb], k] = (AV[pos[bb], k] + c) % P
        # U AV - AM U = 0  <=>  (AV^T kron I - I kron AM) vec U = 0
        C = (np.kron(AV.T, np.eye(d, dtype=np.int64)) - np.kron(np.eye(g, dtype=np.int64), AM)) % P
        CN = (C @ N) % P
        y = nullspace(CN.tolist(), N.shape[1])
        if not y:
            N = np.zeros((nv, 0), dtype=np.int64); break
        N = (N @ np.array(y, dtype=np.int64).T) % P
    sols = [N[:, j] for j in range(N.shape[1])]
    route = {b: None for b in gens}
    frontier = list(gens)
    while frontier:
        nf = []
        for b in frontier:
            for i in range(M.n - 1):
                if len(M.act[i][b]) == 1:
                    c, bb = M.act[i][b][0]
                    if c == 1 and bb not in route:
                        route[bb] = (i, b); nf.append(bb)
        frontier = nf
    assert len(route) == d, "gens do not generate M by monomial moves"
    order = sorted(route, key=lambda b: depth(route, b))
    As = [np.array(M.mat(i), dtype=np.int64) for i in range(M.n - 1)]
    mats = []
    for s in sols:
        img = {b: s[k * d:(k + 1) * d] for k, b in enumerate(gens)}
        for b in order:
            if b not in img:
                i, b0 = route[b]
                img[b] = (As[i] @ img[b0]) % P
        F = np.stack([img[b] for b in range(d)], axis=1) % P
        for A in As:
            assert ((F @ A - A @ F) % P == 0).all(), "extension not H-linear"
        mats.append(F)
    return mats


def depth(route, b):
    n = 0
    while route[b] is not None:
        b = route[b][1]; n += 1
    return n


def summand_count(mats):
    """t = dim End/J(End): rank of trace form of left regular representation."""
    m = len(mats)
    if m == 0:
        return 0
    mats = [np.array(F, dtype=np.int64) % P for F in mats]
    flat = np.array([F.flatten() for F in mats], dtype=np.int64)  # m x d^2
    R, sel = rref(flat)
    assert len(sel) == m, "endomorphism basis not independent"
    inv = mat_inv(flat[:, sel])           # c . flat[:,sel] = target[sel]  => c = target[sel] inv

    def coords(F):
        return (F.flatten()[sel] @ inv) % P

    L = []
    for Fk in mats:
        cols = [coords((Fk @ Fj) % P) for Fj in mats]
        L.append(np.array(cols, dtype=np.int64).T)
    G = [[int(np.trace((L[i] @ L[j]) % P) % P) for j in range(m)] for i in range(m)]
    return rank(G)


def mat_inv(A):
    A = np.array(A, dtype=np.int64)
    m = A.shape[0]
    aug = np.concatenate([A % P, np.eye(m, dtype=np.int64)], axis=1)
    R, piv = rref(aug)
    assert piv[:m] == list(range(m)), "singular"
    return np.array([row[m:] for row in R], dtype=np.int64)


def top_labels(M):
    """All D with Hom(M, C_D) != 0, with dimension (functionals f with f pi_i = [i in D] f)."""
    n = M.n; d = M.d
    mats = [M.mat(i) for i in range(n - 1)]
    out = {}
    for mask in range(1 << (n - 1)):
        eqs = []
        for i in range(n - 1):
            lam = 1 if (mask >> i) & 1 else 0
            # f A_i - lam f = 0 : for each column y: sum_x f_x A[x][y] - lam f_y
            for y in range(d):
                r = [mats[i][x][y] for x in range(d)]
                r[y] = (r[y] - lam) % P
                if any(r):
                    eqs.append(r)
        k = d - rank(eqs) if eqs else d
        if k:
            out[frozenset(i + 1 for i in range(n - 1) if (mask >> i) & 1)] = k
    return out
