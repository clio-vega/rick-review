def adc_sp(D,i,Y):
    out=defaultdict(lambda: sp.Integer(0))
    for w,c in Y.items():
        out[(i,)+w]+=c
        out[w+(i,)]-=c*q**D.pair_lv(i,D.deg(w))
    return {w:sp.expand(c) for w,c in out.items() if sp.expand(c)!=0}

